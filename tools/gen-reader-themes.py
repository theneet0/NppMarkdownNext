#!/usr/bin/env python3
"""Generate offline native and reader catalogs from the vendored theme data."""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
CATALOG=ROOT/'themes/reader-themes.json'

def validate_catalog(data):
    if data.get('schemaVersion')!=1 or not isinstance(data.get('paletteCss'),str):
        raise ValueError('Unsupported or incomplete theme catalog')
    themes=data.get('themes',[])
    if len(themes)!=77 or [t.get('theme') for t in themes[:13]]!=list(range(13)):
        raise ValueError('The 13 stable base enums and 64 variants must be preserved')
    known=set()
    for index,theme in enumerate(themes):
        ids=[theme.get('id'),*theme.get('aliases',[])]
        for id in ids:
            if not isinstance(id,str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*',id) or id in known:
                raise ValueError('Invalid or duplicate theme ID: '+str(id))
            known.add(id)
        if not isinstance(theme.get('label'),str) or not theme['label'] or len(theme['label'])>128:
            raise ValueError('Invalid theme label')
        if type(theme.get('isDark')) is not bool or theme.get('theme') not in range(13):
            raise ValueError('Invalid theme mode or enum')
        if index>=13 and (theme['theme']!=12 or not theme['id'].startswith('bearded-v-')):
            raise ValueError('Variant must retain the Bearded enum')
        if index>=13 and 'body.'+theme['id']+' {' not in data['paletteCss']:
            raise ValueError('Theme has no vendored palette: '+theme['id'])
        for field in ('markdown','markdownOverrides'):
            for role,color in theme.get(field,{}).items():
                if role not in {'heading','bold','italic','inlineCode','quote','link','comment'} or not re.fullmatch(r'#[0-9a-fA-F]{6}',color):
                    raise ValueError('Invalid Markdown color role')

def cpp_wstring(value):
    return 'L'+json.dumps(value,ensure_ascii=True)

def generate(data):
    validate_catalog(data)
    entries=[]
    aliases=[]
    for theme in data['themes']:
        entries.append('    {'+cpp_wstring(theme['id'])+', '+cpp_wstring(theme['label'])+', static_cast<ReaderTheme>('+str(theme['theme'])+'), '+str(theme['isDark']).lower()+'}')
        for alias in theme.get('aliases',[]):
            aliases.append('    if (id == '+cpp_wstring(alias)+') id = '+cpp_wstring(theme['id'])+';')
    native='// Generated by tools/gen-reader-themes.py.\ninline constexpr ThemeCatalogEntry kThemeCatalog[] = {\n'+',\n'.join(entries)+'\n};\n\n'
    native+='inline const ThemeCatalogEntry* FindTheme(std::wstring_view id) noexcept {\n'+'\n'.join(aliases)+'\n    for (const auto& entry : kThemeCatalog) if (entry.id == id) return &entry;\n    return nullptr;\n}\n'
    native+='inline const ThemeCatalogEntry* FindTheme(ReaderTheme theme) noexcept {\n    for (const auto& entry : kThemeCatalog) if (entry.theme == theme) return &entry;\n    return nullptr;\n}\n'
    serialized=json.dumps([{key:t[key] for key in ('id','label','theme','isDark')} for t in data['themes']],ensure_ascii=True,separators=(',',':')).replace('<','\\u003c')
    script='window.READER_THEME_CATALOG = '+serialized+';\n'
    script+='var THEME_LIST = window.READER_THEME_CATALOG.filter(function(t){return t.id.indexOf("bearded-v-")!==0;});\n'
    script+='var THEME_CLASSES = THEME_LIST.filter(function(t){return t.id!=="follow"&&t.id!=="light";}).map(function(t){return t.id;});\n'
    script+='window.BEARDED_VARIANTS = window.READER_THEME_CATALOG.filter(function(t){return t.id.indexOf("bearded-v-")===0;});\n'
    semantic=[]
    selectors={'heading':':is(h1,h2,h3,h4,h5,h6)','bold':'strong','italic':'em','inlineCode':':not(pre) > code','quote':'blockquote','link':'a','comment':'.hljs-comment'}
    for theme in data['themes']:
        roles={**theme.get('markdown',{}),**theme.get('markdownOverrides',{})}
        if not roles:continue
        prefix='body.'+theme['id']
        semantic.append(prefix+' {\n'+''.join('  --reader-'+role+': '+color+';\n' for role,color in roles.items())+'}\n')
        for role in roles:
            semantic.append(prefix+' .doc '+selectors[role]+' { color: var(--reader-'+role+'); }\n')
    palette='// Generated by tools/gen-reader-themes.py.\n'
    for variable,delimiter,value in [('s_readerPaletteCss','PALETTE_CSS',data['paletteCss']),('s_readerCatalogJs','CATALOG_JS',script),('s_readerSemanticCss','SEMANTIC_CSS',''.join(semantic))]:
        if ')'+delimiter+'"' in value:raise ValueError('Raw literal delimiter appears in theme data')
        palette+='inline constexpr const char* '+variable+' = R"'+delimiter+'('+value+')'+delimiter+'";\n'
    return {ROOT/'src/ThemeCatalog.inc':native,ROOT/'src/ThemePalette.inc':palette}

def import_gold(data,extension):
    package=json.loads((extension/'package.json').read_text(encoding='utf-8'))
    provenance=data['provenance']
    if package.get('publisher')!='BeardedBear' or package.get('name')!='beardedtheme' or package.get('version')!=provenance['version']:
        raise ValueError('Extension identity/version differs from the pinned author source')
    path=extension/'themes/bearded-theme-feat-gold-d-raynh.json'
    raw=path.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=provenance['goldFileSha256']:
        raise ValueError('Gold source hash differs from the pinned author source')
    source=json.loads(raw)
    scopes={'heading':'entity.name.section','bold':'markup.bold','italic':'markup.italic','inlineCode':'markup.inline.raw.string.markdown','quote':'markup.quote','link':'markup.underline.link','comment':'comment'}
    roles={}
    for role,scope in scopes.items():
        for token in source['tokenColors']:
            defined=token.get('scope',[])
            if isinstance(defined,str):defined=[s.strip() for s in defined.split(',')]
            if scope in defined and 'foreground' in token.get('settings',{}):roles[role]=token['settings']['foreground']
        if role not in roles:raise ValueError('Missing author scope: '+scope)
    next(t for t in data['themes'] if t['id']=='bearded-v-gold-d-raynh')['markdown']=roles

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--vscode-extension',type=Path)
    args=parser.parse_args()
    data=json.loads(CATALOG.read_text(encoding='utf-8'))
    if args.vscode_extension:
        import_gold(data,args.vscode_extension)
        validate_catalog(data)
        if not args.check:CATALOG.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    outputs=generate(data)
    stale=[]
    for path,content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=content:stale.append(str(path))
        else:path.write_text(content,encoding='utf-8')
    if stale:
        print('Generated theme data is stale: '+'; '.join(stale),file=sys.stderr)
        return 1
    print('Theme catalog verified: 77 choices' if args.check else 'Generated 77 theme choices and Gold Markdown roles')
    return 0

if __name__=='__main__':
    try:sys.exit(main())
    except (OSError,ValueError,KeyError) as error:
        print('Theme generation failed: '+str(error),file=sys.stderr)
        sys.exit(1)
